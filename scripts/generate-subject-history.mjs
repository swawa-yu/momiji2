import fs from 'node:fs/promises';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

import {
  applyHistoryArtifact,
  validateHistoryDataDir,
} from './validate-history-artifacts.mjs';

const root = process.cwd();
const defaultDataDir = path.join(root, 'data');
const defaultOutputPath = path.join(
  root,
  'src',
  'subject',
  'activeSubjectHistory.ts'
);

export async function loadDisplayHistory(dataDir = defaultDataDir) {
  await validateHistoryDataDir(dataDir);
  const historyRoot = path.join(dataDir, 'history');
  let years;
  try {
    years = (await fs.readdir(historyRoot, { withFileTypes: true }))
      .filter((entry) => entry.isDirectory() && /^\d{4}$/.test(entry.name))
      .map((entry) => entry.name)
      .sort();
  } catch (error) {
    if (error.code === 'ENOENT') return [];
    throw error;
  }
  const entries = [];
  for (const year of years) {
    const directory = path.join(historyRoot, year);
    const index = JSON.parse(
      await fs.readFile(path.join(directory, 'index.json'), 'utf8')
    );
    let current = JSON.parse(
      await fs.readFile(path.join(dataDir, index.baseline.dataFile), 'utf8')
    );
    for (const pointer of index.artifacts) {
      const artifact = JSON.parse(
        await fs.readFile(path.join(directory, pointer.dataFile), 'utf8')
      );
      const next = applyHistoryArtifact(current, artifact);
      const changes = artifact.changes.map((change) => ({
        type: change.type,
        lectureCode: change.lectureCode,
        titleBefore: current[change.lectureCode]?.['授業科目名'] ?? null,
        titleAfter: next[change.lectureCode]?.['授業科目名'] ?? null,
        fields: change.type === 'changed' ? change.fields : [],
      }));
      entries.push({
        academicYear: artifact.target.academicYear,
        baseRetrievedAt: artifact.base.retrievedAt,
        targetRetrievedAt: artifact.target.retrievedAt,
        baseSubjectCount: artifact.base.subjectCount,
        targetSubjectCount: artifact.target.subjectCount,
        addedCount: changes.filter((change) => change.type === 'added').length,
        removedCount: changes.filter((change) => change.type === 'removed')
          .length,
        changedCount: changes.filter((change) => change.type === 'changed')
          .length,
        changes,
      });
      current = next;
    }
  }
  return entries.reverse();
}

export function renderSubjectHistory(entries) {
  return `// Generated from validated data/history indexes.
// Do not edit this file directly.

export type SubjectHistoryFieldChange = {
  readonly field: string;
  readonly before: string;
  readonly after: string;
};

export type SubjectHistoryChange = {
  readonly type: 'added' | 'removed' | 'changed';
  readonly lectureCode: string;
  readonly titleBefore: string | null;
  readonly titleAfter: string | null;
  readonly fields: readonly SubjectHistoryFieldChange[];
};

export type SubjectHistoryEntry = {
  readonly academicYear: string;
  readonly baseRetrievedAt: string;
  readonly targetRetrievedAt: string;
  readonly baseSubjectCount: number;
  readonly targetSubjectCount: number;
  readonly addedCount: number;
  readonly removedCount: number;
  readonly changedCount: number;
  readonly changes: readonly SubjectHistoryChange[];
};

export const subjectHistory: readonly SubjectHistoryEntry[] = ${JSON.stringify(entries, null, 2)};
`;
}

export async function generateSubjectHistory({
  dataDir = defaultDataDir,
  outputPath = defaultOutputPath,
  check = false,
} = {}) {
  const expected = renderSubjectHistory(await loadDisplayHistory(dataDir));
  if (check) {
    let actual;
    try {
      actual = await fs.readFile(outputPath, 'utf8');
    } catch (error) {
      if (error.code === 'ENOENT')
        throw new Error(`Generated subject history is missing: ${outputPath}`);
      throw error;
    }
    if (actual !== expected)
      throw new Error('Generated subject history is out of date.');
    return;
  }
  await fs.mkdir(path.dirname(outputPath), { recursive: true });
  await fs.writeFile(outputPath, expected);
}

async function main() {
  const arguments_ = process.argv.slice(2);
  const check = arguments_.includes('--check');
  if (arguments_.some((argument) => argument !== '--check'))
    throw new Error(
      'Usage: node scripts/generate-subject-history.mjs [--check]'
    );
  await generateSubjectHistory({ check });
  console.log(
    check
      ? 'Subject history display data is up to date.'
      : 'Generated src/subject/activeSubjectHistory.ts'
  );
}

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(process.argv[1]).href
) {
  main().catch((error) => {
    console.error(error.message);
    process.exit(1);
  });
}
